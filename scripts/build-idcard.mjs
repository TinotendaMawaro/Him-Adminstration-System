// Bundles the QR library + the card renderer into one file the React portals AND the Filament portals can load:
//   node scripts/build-idcard.mjs   ->   public/js/him-idcard.js
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const qr = readFileSync(path.join(root, 'node_modules/qrcode-generator/qrcode.js'), 'utf8');
const core = readFileSync(path.join(root, 'resources/js/lib/idCard.core.js'), 'utf8');

// qrcode-generator is UMD and only exports through CommonJS, so give it a private `module` and publish `window.qrcode` ourselves.
const out = `/* HIM ID card — generated by scripts/build-idcard.mjs. Do not edit; edit resources/js/lib/idCard.core.js. */\n(function(){var define=undefined,exports={},module={exports:exports};\n${qr}\nwindow.qrcode=module.exports;\n})();\n${core}\n`;

mkdirSync(path.join(root, 'public/js'), { recursive: true });
writeFileSync(path.join(root, 'public/js/him-idcard.js'), out);
console.log('public/js/him-idcard.js', Math.round(out.length / 1024) + ' KB');
